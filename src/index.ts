/**
 * Worker entry — routing and the edge facts. All judgement lives in ingest.ts; this file only
 * turns an HTTP request into an EdgeContext and a result back into a status code.
 *
 * Build order that keeps every step verifiable:
 *   1. POST /e  → validate against schema.ts, reject unknown `source`, 204. No sinks yet. ✔
 *   2. Analytics Engine sink, with the BLOB_SLOTS mapping. ✔ (no ctx.waitUntil — see the sink)
 *   3. /v1/stats reading back through the SQL API — proves the round trip. ✔
 *   4. The web snippet ✔ (served at /sda.js), then the Swift snippet.
 *   5. Only then Pipelines → R2 Iceberg (v2).
 */
import { Hono } from "hono";
import { accessIdentity } from "./access";
import { deriveAnon } from "./anon";
import { DASHBOARD, DASHBOARD_CACHE_SECONDS } from "./dashboard";
import { ingest } from "./ingest";
import { isRegisteredOrigin } from "./registry";
import { buildOpenReport, OPEN_CACHE_SECONDS, OPEN_PAGE, OPEN_PAGE_CACHE_SECONDS } from "./open";
import { handleMcp } from "./mcp";
import { fetchOverview } from "./overview";
import { writeEvents } from "./sinks/analytics-engine";
import { fetchStats } from "./stats";
import { SNIPPET, SNIPPET_CACHE_SECONDS, SNIPPET_VERSION } from "./snippet";
import { readCampaigns, readTotals } from "./stores/db";
import { dayBefore, utcDay } from "./stores/schema";
import { syncAppStore } from "./stores/sync";

/**
 * `Env` is generated by `make gen` (wrangler types) from wrangler.jsonc — the bindings are not
 * restated here, so a dataset renamed in the config breaks the build instead of drifting.
 * EVENTS is the Analytics Engine dataset: hot store, 3-month retention.
 */
type Bindings = Env;

/**
 * A full batch is 250 events; 1 MB is far above any honest one and far below anything worth
 * spending CPU parsing.
 *
 * Advisory, not a wall: it reads content-length, and a chunked request need not send one. The
 * real ceiling is the platform's request limit — this only stops the cheap, honest mistakes.
 */
const MAX_BODY_BYTES = 1_000_000;

/**
 * Is this one of us? `INTERNAL_IPS` is a comma-separated secret — home, office, phone tether.
 *
 * An exact match only, no ranges: a CIDR parser is more code than this whole feature deserves,
 * and a too-wide range silently deletes real visitors, which is worse than counting yourself.
 */
export function isInternal(list: string | undefined, ip: string | undefined): boolean {
  if (list === undefined || list === "" || ip === undefined) return false;
  return list.split(",").some((entry) => entry.trim() === ip);
}

/** A week is the question that gets asked; anything else is an explicit `?days=`. */
const DEFAULT_WINDOW_DAYS = 7;

/**
 * Long enough to survive a refresh storm, short enough that "now" still means now.
 *
 * Two minutes rather than one since the overview grew to six SQL queries: reads are metered at
 * 10k/day on the free plan, which is one full recompute every 52 seconds sustained. A dashboard
 * left open on a second monitor is exactly the thing that would spend that budget on a number
 * which has not changed.
 */
const STATS_CACHE_SECONDS = 120;

/**
 * Cache keys carry the deployment id, so shipping new code invalidates every cached response
 * instead of serving the previous shape until its TTL runs out. That failure is silent and
 * looks like missing data, which is the worst way for a dashboard to be wrong.
 */
function cacheKey(c: { env: Bindings; req: { url: string } }): Request {
  const url = new URL(c.req.url);
  url.searchParams.set("__v", c.env.VERSION?.id ?? "dev");
  return new Request(url.toString());
}

const app = new Hono<{ Bindings: Bindings }>();

/**
 * The read side shows the business: traffic per property, which products are alive. It must
 * not be world-readable.
 *
 * This is a shared key, not authentication — the honest answer is Cloudflare Access in front
 * of `/` and `/v1/*`, which is free at this scale, is real SSO, and needs no code. Until that
 * is configured this keeps the numbers off the open internet, and when DASHBOARD_KEY is unset
 * it refuses rather than defaulting to open: a dashboard that is public by accident is worse
 * than one that is broken by configuration.
 *
 * `/e` and `/sda.js` are deliberately outside this — a beacon cannot carry a secret, and a
 * script tag must be loadable by anyone.
 */
function authorized(c: { env: Bindings; req: { query: (k: string) => string | undefined; header: (k: string) => string | undefined } }): boolean {
  const expected = c.env.DASHBOARD_KEY;
  if (expected === undefined || expected === "") return false;
  const given = c.req.query("k") ?? c.req.header("authorization")?.replace(/^Bearer /, "");
  return given === expected;
}

/**
 * Two doors, and both must open onto the same room.
 *
 * Access is the real one — it is SSO, it expires, and it knows who you are. The shared key
 * stays because a beacon, a cron and a CLI cannot do SSO, and because locking oneself out of
 * the dashboard while debugging Access would be a poor kind of security.
 *
 * Order matters: the key is checked first because it costs nothing, and the Access path only
 * fetches keys when there is a token to check.
 *
 * ЧЕСТНАЯ ОГОВОРКА. Пока Access стоит перед этими путями, ключ на них недостижим снаружи:
 * Access отвечает редиректом на логин ДО того, как запрос дойдёт до воркера. То есть «вторая
 * дверь» работает только внутри — для крона, для тестов и для того дня, когда приложение
 * Access выключат или сузят. Машинный доступ снаружи — это Service Auth и служебный токен, а
 * не общий ключ.
 */
async function permitted(c: {
  env: Bindings;
  req: { query: (k: string) => string | undefined; header: (k: string) => string | undefined };
}): Promise<boolean> {
  if (authorized(c)) return true;
  const who = await accessIdentity(c.env, c.req.header("cf-access-jwt-assertion"), Date.now());
  return who !== undefined;
}

app.use("/dashboard", async (c, next) => {
  if (!(await permitted(c))) return c.text("not found", 404);
  await next();
});

/**
 * The analytics as tools an agent can call. Outside the /v1/* middleware because MCP carries
 * its own auth convention — a bearer token and a 401 with WWW-Authenticate — which is what an
 * MCP client knows how to handle. Same DASHBOARD_KEY behind it.
 */
app.all("/mcp", (c) => handleMcp(c.req.raw, c.env, Date.now()));

app.use("/v1/*", async (c, next) => {
  if (!(await permitted(c))) return c.json({ error: "unauthorized" }, 401);
  await next();
});

/**
 * The open-startup page. Public on purpose, and deliberately NOT under /v1/* — that prefix is
 * keyed, and the two must not be one middleware edit away from swapping places.
 *
 * A 30-day window and a 15-minute cache: nobody refreshes a public metrics page for a live
 * number, and read budget spent here is read budget not available to the dashboard.
 */
const OPEN_WINDOW_DAYS = 30;

app.get("/open", (c) => {
  c.header("content-type", "text/html; charset=utf-8");
  c.header("cache-control", `public, max-age=${OPEN_PAGE_CACHE_SECONDS}`);
  return c.body(OPEN_PAGE);
});

app.get("/open.json", async (c) => {
  const cache = caches.default;
  const key = cacheKey(c);
  const cached = await cache.match(key);
  if (cached !== undefined) return cached;

  const report = await buildOpenReport(c.env, OPEN_WINDOW_DAYS, Date.now());
  const response = c.json(report);
  response.headers.set("cache-control", `public, max-age=${OPEN_CACHE_SECONDS}`);
  // Anyone may read it — that is the point — so anyone may fetch it from their own page too.
  response.headers.set("access-control-allow-origin", "*");
  c.executionCtx.waitUntil(cache.put(key, response.clone()));
  return response;
});

/**
 * The dashboard. Never indexed, never cached publicly — it is one operator's view.
 *
 * On `/dashboard` rather than `/`, and that is the whole point: Cloudflare Access protects a
 * hostname or a path PREFIX, so an application defined on the bare host would sit in front of
 * `/e` and `/sda.js` too. Every counter on every site would start receiving a login page
 * instead of a 204 — silently, because a beacon never looks at the answer. Giving the private
 * side its own prefix is what makes "put SSO in front of it" a configuration change rather
 * than an outage.
 */
app.get("/dashboard", (c) => {
  c.header("content-type", "text/html; charset=utf-8");
  c.header("cache-control", "private, no-store");
  return c.body(DASHBOARD);
});

/** The old address, kept working: it is in bookmarks and in half this repository's docs. */
app.get("/", (c) => c.redirect(`/dashboard${new URL(c.req.url).search}`, 302));

app.get("/health", (c) => c.json({ ok: true, stage: "ingest" }));

/**
 * A favicon, so every dashboard load stops logging a 404 against itself. An SVG in the source
 * rather than a binary in a bucket: it is nine bytes of shape, and a Worker that needs an asset
 * pipeline to draw a square has the wrong kind of dependency.
 */
const FAVICON =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">' +
  '<rect width="32" height="32" rx="7" fill="#111"/>' +
  '<rect x="7" y="17" width="4" height="8" fill="#fff"/>' +
  '<rect x="14" y="12" width="4" height="13" fill="#fff"/>' +
  '<rect x="21" y="7" width="4" height="18" fill="#fff"/></svg>';

app.get("/favicon.ico", (c) => {
  c.header("content-type", "image/svg+xml");
  c.header("cache-control", "public, max-age=604800");
  return c.body(FAVICON);
});

/**
 * The web snippet. Served from here so the thirteen sites embed a URL once and never need
 * editing again — every later change to how a browser reports is a deploy.
 */
app.get("/sda.js", (c) => {
  const etag = `"sda-${SNIPPET_VERSION}"`;
  c.header("content-type", "application/javascript; charset=utf-8");
  // `stale-while-revalidate` is what makes the hour survivable: a returning visitor runs the
  // cached copy instantly AND the browser fetches the new one in the background, so a fix
  // reaches the second page view instead of waiting out the full hour. Without it, deploying
  // a snippet change and then verifying it in your own browser proves nothing for an hour —
  // which is exactly how this was found.
  c.header(
    "cache-control",
    `public, max-age=${SNIPPET_CACHE_SECONDS}, stale-while-revalidate=86400`,
  );
  // SNIPPET_VERSION called itself "the cache key visitors actually see" while appearing in no
  // response at all. It does now: revalidation costs a 304 with no body instead of 2 KB.
  c.header("etag", etag);
  // The one file here that a third-party origin must be allowed to load.
  c.header("access-control-allow-origin", "*");
  if (c.req.header("if-none-match") === etag) return c.body(null, 304);
  return c.body(SNIPPET);
});

/**
 * Ingest. One endpoint for web beacons and mobile flushes — same schema, so a landing visit
 * and an app launch are comparable without a join.
 */
app.post("/e", async (c) => {
  const declared = Number(c.req.header("content-length") ?? 0);
  if (declared > MAX_BODY_BYTES) {
    return c.json({ error: "body_too_large", limit: MAX_BODY_BYTES }, 413);
  }

  // Read as text and parse by hand rather than c.req.json(): navigator.sendBeacon sends
  // text/plain, and refusing on content-type would break the web snippet before it is written.
  let body: unknown;
  try {
    body = JSON.parse(await c.req.text());
  } catch {
    return c.json({ error: "invalid_json" }, 400);
  }

  const now = Date.now();
  const userAgent = c.req.header("user-agent");

  // Our own visits. Every counter has this problem and most solve it with a localStorage flag,
  // which is precisely the thing this project promises on every privacy page it is not doing.
  // So it is decided at the edge instead, from a secret that never enters the public repo.
  //
  // Dropped, not marked: a marked event costs a blob slot and a WHERE clause in every query
  // written from now until the end of the project, to hide rows nobody ever wants to see.
  // The failure mode is honest — if the list is wrong, your own visits keep showing up.
  //
  // 204 all the same. The browser must not learn whether it was counted, and a beacon has
  // nothing useful to do with the answer.
  if (isInternal(c.env.INTERNAL_IPS, c.req.header("cf-connecting-ip"))) {
    return c.body(null, 204);
  }

  const result = ingest(body, {
    now,
    // cf.country is absent in local dev; the header is the same edge-controlled fact and makes
    // this path testable without a real colo. Neither can be set by a browser.
    country: c.req.raw.cf?.country?.toString() ?? c.req.header("cf-ipcountry"),
    userAgent,
    // The IP is used to derive the id and is never stored — see anon.ts.
    anon: await deriveAnon(c.env.ANON_SALT, now, c.req.header("cf-connecting-ip"), userAgent),
  });

  if (!result.ok) return c.json(result.body, result.status);

  // Not a visitor: a preview deploy, a dev server, or the tag pasted somewhere it does not
  // belong. Checked AFTER validation so a misconfigured site still gets a real error about a
  // real mistake instead of a silent 204 that hides both.
  const origin = c.req.header("origin");
  const counted = result.events.filter((e) => isRegisteredOrigin(e.source, origin));
  if (counted.length > 0) writeEvents(c.env.EVENTS, counted);

  // Nothing useful to say, and it keeps the beacon cheap.
  return c.body(null, 204);
});

/**
 * Read-only stats for the dashboard. Never writes.
 *
 * Cached at the edge for a minute because read queries are metered — 10k/day on the free plan
 * — and a dashboard left open on a second monitor would otherwise spend the whole budget on
 * a number that has not changed.
 */
app.get("/v1/stats", async (c) => {
  const cache = caches.default;
  const key = cacheKey(c);
  const cached = await cache.match(key);
  if (cached !== undefined) return cached;

  const result = await fetchStats(c.env, Number(c.req.query("days") ?? DEFAULT_WINDOW_DAYS));
  if (!result.ok) return c.json(result.body, result.status);

  const response = c.json(result.stats);
  response.headers.set("cache-control", `private, max-age=${STATS_CACHE_SECONDS}`);
  c.executionCtx.waitUntil(cache.put(key, response.clone()));
  return response;
});

/**
 * Everything the dashboard draws, in one round trip: our events plus Cloudflare's edge counts,
 * assembled but never summed. Cached for the same reason /v1/stats is — read queries are
 * metered, and this one makes three upstream calls rather than one.
 */
app.get("/v1/overview", async (c) => {
  const cache = caches.default;
  const key = cacheKey(c);
  const cached = await cache.match(key);
  if (cached !== undefined) return cached;

  const result = await fetchOverview(
    c.env,
    Number(c.req.query("days") ?? DEFAULT_WINDOW_DAYS),
    Date.now(),
  );
  if (!result.ok) return c.json(result.body, result.status as 400 | 500 | 502);

  const response = c.json(result.overview);
  response.headers.set("cache-control", `private, max-age=${STATS_CACHE_SECONDS}`);
  c.executionCtx.waitUntil(cache.put(key, response.clone()));
  return response;
});

/**
 * What the stores report about themselves. A separate endpoint from /v1/stats on purpose: these
 * numbers come from a different party, are exact where ours are sampled, and are never added to
 * ours. Keeping them on one endpoint would invite exactly that addition.
 */
app.get("/v1/stores", async (c) => {
  const days = Number(c.req.query("days") ?? DEFAULT_WINDOW_DAYS);
  const to = dayBefore(utcDay(Date.now()), 1);
  const from = dayBefore(to, Math.max(1, days) - 1);
  const [totals, campaigns] = await Promise.all([
    readTotals(c.env.STORES, from, to),
    readCampaigns(c.env.STORES, from, to),
  ]);
  return c.json({ from, to, totals, campaigns });
});

/**
 * Run the daily job now. It exists because a job observable only by waiting until tomorrow is a
 * job nobody can debug — and because the first run after configuring the key should be a
 * deliberate act with its output on screen, not a surprise at 05:00.
 */
app.post("/v1/stores/sync", async (c) => {
  const from = c.req.query("from");
  const result = await syncAppStore(c.env, Date.now(), from);
  return c.json(result);
});

export default {
  fetch: app.fetch,
  /**
   * The cron. Errors are logged and swallowed per store: one store failing must not stop the
   * others, and a scheduled handler that throws is retried by the platform in a way that would
   * re-fetch the same window again for no gain.
   */
  async scheduled(_event: ScheduledController, env: Bindings, ctx: ExecutionContext) {
    ctx.waitUntil(
      syncAppStore(env, Date.now())
        .then((r) => console.log("store sync", JSON.stringify(r)))
        .catch((e: unknown) => console.error("store sync failed", String(e))),
    );
  },
} satisfies ExportedHandler<Bindings>;
